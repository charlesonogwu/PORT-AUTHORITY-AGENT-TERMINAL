#!/usr/bin/env node
/**
 * Sync the built React dashboard (dashboard-ui/portpilot-dashboard/dist/index.html)
 * into src/ui/dashboard.ts as an exported string constant.
 *
 * Run after the Vite single-file build:
 *
 *   cd dashboard-ui/portpilot-dashboard && npm run build
 *   cd ../.. && node scripts/sync-dashboard-html.mjs
 *
 * Or use the wrapper npm script `build:dashboard` which does both.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

const HTML_PATH = join(ROOT, "dashboard-ui", "portpilot-dashboard", "dist", "index.html");
const OUT_PATH = join(ROOT, "src", "ui", "dashboard.ts");

let html;
try {
  html = readFileSync(HTML_PATH, "utf8");
} catch (err) {
  console.error(
    `sync-dashboard-html: cannot read ${HTML_PATH}\n` +
      `  Did you forget to run the dashboard build first?\n` +
      `  Try: cd dashboard-ui/portpilot-dashboard && npm install && npm run build\n` +
      `  Underlying error: ${err.message}`,
  );
  process.exit(1);
}

// Escape backticks, backslashes, and ${ for template-literal embedding.
const escaped = html
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

const sizeKb = (html.length / 1024).toFixed(1);
const generated = `/**
 * Auto-generated by scripts/sync-dashboard-html.mjs.
 *
 * Source: dashboard-ui/portpilot-dashboard/dist/index.html
 * Size:   ${sizeKb} KB
 *
 * DO NOT EDIT BY HAND.
 * To regenerate: \`npm run build:dashboard\` from the project root.
 */

export const DASHBOARD_HTML = \`${escaped}\`;
`;

writeFileSync(OUT_PATH, generated, "utf8");
console.log(
  `sync-dashboard-html: wrote ${html.length} chars (${sizeKb} KB) → ${relative(ROOT, OUT_PATH)}`,
);
